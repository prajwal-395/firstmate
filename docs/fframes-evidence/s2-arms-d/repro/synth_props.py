"""Synthetic props for the S2 arms-d lowerings (census G2, last group).

No real geo-podcast card uses comparison_bars, counter_roll,
step_counter, pointer_annotation, context_stamp or website_panel, so
every case here is synthetic - but each quotes a real plan shape
(copy, data payload, anchor, entrance) rather than a toy. Durations
are short (48-72f); the roll span, stagger and growth curves are all
exercised inside them.

The website capture is generated by ``make_capture.py`` into this
directory (a project-supplied still, the way brand_assets supplies
one); the FFrames side reads it by absolute path while the Remotion
side reads it staged under ``public/brand/`` (see README - same pixels,
two address forms, the only props difference between the sides).
"""

SAFE_1080x1920 = {"top": 220, "right": 60, "bottom": 320, "left": 60}


def _element(kind, **overrides):
    element = {
        "element": kind,
        "anchor": "centre",
        "row": 0,
        "runs": [],
        "color": "#7CFC00",
        "entrance": "fade",
        "exit": "fade",
        "startFrame": 0,
        "durationFrames": 60,
        "footprint": 1.0,
        "timelineProgressStart": 0.1,
        "timelineProgressEnd": 0.2,
        "emphasis": None,
        "data": {},
    }
    element.update(overrides)
    return element


def _props(elements, duration, width=1080, height=1920,
           safe_area=None):
    return {
        "elements": elements,
        "fps": 30,
        "width": width,
        "height": height,
        "safeArea": dict(safe_area or SAFE_1080x1920),
        "durationInFrames": duration,
    }


def stamp():
    return _props([_element(
        "context_stamp", anchor="top_centre",
        runs=[{"text": "Austin, Texas - 6:40 AM",
               "type_role": "micro", "uppercase": False}],
        color="#1D4ED8",
        entrance="fade", exit="fade",
        durationFrames=60,
    )], 60)


