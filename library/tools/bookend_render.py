"""Render the composition-mode bookends a spine declares.

A bookend declared with ``asset:`` already exists and nothing here touches
it.  A bookend declared with ``composition:`` has to become a file before
``compile_manifest`` can put it on V1, and this is where that happens.

Two shapes, because the captain's premade cards live outside this repo
(decision record 2026-08-17):

* an ENGINE composition - one of ``ENGINE_BOOKEND_COMPOSITIONS``, already
  registered in ``remotion-subtitles/src/Root.tsx`` - renders through the
  committed entry point;
* a PROJECT composition - a ``.tsx`` the project owns, named by
  ``source:`` - is staged into the Remotion project **verbatim** and
  rendered through a generated entry point that registers just that one
  composition.  Nothing rewrites the file: it is the captain's asset, and
  the engine's job is to render it, not to edit it.  Sibling assets
  (the logo PNG beside ``LucieEndCard.tsx``, say) are copied into
  ``public/`` so ``staticFile()`` resolves.

Staged files are build output.  The composition and its entry point go to
``src/staged/`` and the sibling assets to the ``public/`` root - both
gitignored, both rewritten on every run, so a stale copy can never be what
renders.

**This replaces ``library/tools/execution/import_endcard.py``**, which
imported a rendered end card straight into a running Resolve and appended
it to V1 after the fact.  Everything that route knew - find the media,
place it at the end of the edit, keep the source timebase - the manifest
route does too, and it does it where ``manifest_validator`` and the render
QA in step 6.02 can see the result.  See section 5 of
``docs/PIPELINE_PLAN.md``.
"""
from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys

from library.tools.bookends import block_bookend, bookend_blocks
from library.tools.remotion_batch import (
    RemotionBatchError,
    RenderJob,
    render_batch,
)

# Where staged project compositions and their generated entry points go.
STAGED_DIRNAME = os.path.join("src", "staged")

# Remotion render can take a while on a cold bundle; a 5s card is not the
# reason a run should hang forever either.
RENDER_TIMEOUT_SECONDS = 300


class BookendRenderError(RuntimeError):
    """A declared bookend could not be turned into a file."""


def _entry_source(composition: str, module: str) -> str:
    """A Remotion entry point registering one staged composition.

    Duration, fps and dimensions come from the props the pipeline passes,
    the same way every other composition in this project does it.
    """
    return f"""// GENERATED by library/tools/bookend_render.py - do not edit.
// Registers one staged project composition so it can be rendered on its
// own, without touching the committed Root.tsx.
import {{ registerRoot, Composition }} from "remotion";
import type {{ CalculateMetadataFunction }} from "remotion";
import {{ {composition} }} from "./{module}";

const calculateMetadata: CalculateMetadataFunction<any> = async ({{ props }}) => ({{
  durationInFrames: props.durationInFrames,
  fps: props.fps,
  width: props.width,
  height: props.height,
}});

const Root: React.FC = () => (
  <>
    <Composition
      id="{composition}"
      component={{{composition} as any}}
      durationInFrames={{150}}
      fps={{30}}
      width={{1080}}
      height={{1920}}
      defaultProps={{{{}} as any}}
      calculateMetadata={{calculateMetadata}}
    />
  </>
);

registerRoot(Root);
"""


def stage_project_composition(source_path: str, composition: str,
                              remotion_dir: str) -> str:
    """Copy a project composition in verbatim and write its entry point.

    Returns the entry point path to hand to ``npx remotion render``.
    """
    if not os.path.isfile(source_path):
        raise BookendRenderError(
            f"bookend composition source not found: {source_path}")

    staged_dir = os.path.join(remotion_dir, STAGED_DIRNAME)
    os.makedirs(staged_dir, exist_ok=True)

    module = composition
    shutil.copyfile(source_path, os.path.join(staged_dir, f"{module}.tsx"))

    # Sibling assets the composition reaches for with staticFile(), which
    # resolves against public/ and nowhere else.
    source_dir = os.path.dirname(os.path.abspath(source_path))
    public_dir = os.path.join(remotion_dir, "public")
    os.makedirs(public_dir, exist_ok=True)
    for name in sorted(os.listdir(source_dir)):
        sibling = os.path.join(source_dir, name)
        if os.path.isfile(sibling) and not name.endswith((".tsx", ".ts")):
            shutil.copyfile(sibling, os.path.join(public_dir, name))

    entry_path = os.path.join(staged_dir, f"{module}Entry.tsx")
    with open(entry_path, "w", encoding="utf-8") as f:
        f.write(_entry_source(composition, module))
    return entry_path


def bookend_props(bookend: dict, fps: int, width: int, height: int) -> dict:
    """Props for the composition, declared values over the frame geometry.

    Deterministic by construction: same declaration, same props, so the
    same card renders byte-for-byte on a re-run.
    """
    duration_frames = max(1, round(bookend["duration_seconds"] * fps))
    props = {
        "fps": fps,
        "width": width,
        "height": height,
        "durationInFrames": duration_frames,
    }
    props.update(bookend.get("props") or {})
    return props


def render_bookend(bookend: dict, remotion_dir: str, fps: int = 30,
                   *, width: int, height: int,
                   project_folder: str = "") -> dict:
    """Render one composition-mode bookend to the path the spine named.

    `width`/`height` are the DECLARED delivery frame and have no default:
    a default is what let bookends render vertical onto a landscape
    timeline. The caller states the frame - see
    library/tools/delivery_format.py.

    An ENGINE composition - one registered in the committed
    ``remotion-subtitles/src/Root.tsx`` - goes through the shared batch
    renderer (``library/tools/remotion_batch.py``): one bundle for the
    batch instead of one bundle-and-launch per card. Where the
    HyperFrames engine is selected (the project wins over the user -
    ``library/tools/graphics_renderer.py``) and the composition HAS a
    HyperFrames form, it draws through that instead, stated in the
    output.

    A PROJECT composition - a ``.tsx`` the project owns, staged into a
    generated entry point that registers just that one composition -
    stays on ``npx remotion render``, deliberately, on EITHER engine.
    The batch bundles the committed entry point (``src/index.ts``); a
    staged composition lives behind a different bundle root, so it
    cannot join a batch without a protocol the batch does not have -
    and it has no HyperFrames form at all. That is the
    different-composition-root case: a single render that legitimately
    stays on the CLI, stated rather than silently left.
    """
    composition = bookend.get("composition")
    if not composition:
        raise BookendRenderError(
            f"bookend '{bookend.get('slot')}' has no composition to render")

    out_path = bookend["asset_path"]
    os.makedirs(os.path.dirname(out_path), exist_ok=True)

    props = bookend_props(bookend, fps, width, height)
    props_path = os.path.join(
        os.path.dirname(out_path), f"{bookend['slot']}_props.json")
    with open(props_path, "w", encoding="utf-8") as f:
        json.dump(props, f, indent=2, sort_keys=True)

    if bookend.get("source_path"):
        _render_one_cli(bookend, composition, remotion_dir, out_path,
                        props_path, project_folder=project_folder)
    elif _hyperframes_draws(composition, project_folder):
        _render_engine_hyperframes(bookend, composition, remotion_dir,
                                   out_path, props, project_folder)
    else:
        _render_engine_batch([(bookend, props, out_path)], remotion_dir)

    return {
        "slot": bookend["slot"],
        "composition": composition,
        "asset_path": out_path,
        "props_path": props_path,
        "bytes": os.path.getsize(out_path),
    }


def _hyperframes_draws(composition: str, project_folder: str) -> bool:
    """True when the selected engine draws this composition via HyperFrames.

    Two gates: the engine is selected, AND the composition has a
    HyperFrames form. Either one failing means Remotion draws - the
    first failing is today's path unchanged, the second (MotionGraphics
    until its port lands) is the stated fallback, never a silent one.
    """
    from library.tools import graphics_renderer as _engines
    from library.tools import hyperframes_render as _hf
    if not _engines.is_hyperframes(project_folder or None):
        return False
    return _hf.hyperframes_template(composition) is not None


def _render_engine_hyperframes(bookend: dict, composition: str,
                               remotion_dir: str, out_path: str,
                               props: dict, project_folder: str) -> None:
    """Render one engine-composition bookend through HyperFrames.

    Raises :class:`BookendRenderError` naming the slot, the way the CLI
    path always has: a missing card is a hole in the picture, never a
    warning.
    """
    import sys as _sys

    from library.tools import graphics_renderer as _engines
    from library.tools import hyperframes_render as _hf
    print(f"    engine: HyperFrames for '{bookend['slot']}' "
          f"({composition} has a HyperFrames form; selected by "
          f"{_engines.USER_SETTING_KEY} or the project's "
          f"pipeline.graphics_renderer)", file=_sys.stderr)
    try:
        _hf.render_one_card(
            composition, props, out_path,
            os.path.dirname(os.path.abspath(out_path)),
            project_folder or "",
            os.path.dirname(os.path.abspath(remotion_dir)))
    except (_hf.HyperFramesUnavailable,
            _hf.HyperFramesRenderError) as exc:
        raise BookendRenderError(
            f"bookend '{bookend['slot']}' ({composition}) HyperFrames "
            f"render failed: {exc}") from exc
    if not os.path.exists(out_path):
        raise BookendRenderError(
            f"bookend '{bookend['slot']}' ({composition}) reported "
            f"success but wrote no file at {out_path}")


def _render_one_cli(bookend: dict, composition: str, remotion_dir: str,
                    out_path: str, props_path: str,
                    project_folder: str = "") -> None:
    """One ``npx remotion render`` of a project-owned staged composition.

    This is the deliberate CLI remainder: see :func:`render_bookend`.
    On the HyperFrames engine this is also the stated fallback - a
    project-owned ``.tsx`` has no HyperFrames form, so it draws through
    Remotion BY NAME rather than approximately or not at all.
    """
    from library.tools import graphics_renderer as _engines
    if _engines.is_hyperframes(project_folder or None):
        print(f"    engine: Remotion for '{bookend['slot']}' "
              f"({composition} is a project-owned .tsx with no "
              f"HyperFrames form; selected engine is HyperFrames, "
              f"so this card falls back BY NAME, not silently)",
              file=sys.stderr)
    command = ["npx", "remotion", "render"]
    command.append(stage_project_composition(
        bookend["source_path"], composition, remotion_dir))
    command += [
        composition, out_path,
        "--props", props_path,
        "--codec", "prores",
        "--prores-profile", "4444",
        "--image-format", "png",
    ]

    try:
        result = subprocess.run(
            command, cwd=remotion_dir, capture_output=True,
            # The return code is judged below, with the stderr in the
            # message: a raised CalledProcessError would throw it away.
            check=False,
            text=True, encoding="utf-8", errors="replace",
            timeout=RENDER_TIMEOUT_SECONDS,
        )
    except subprocess.TimeoutExpired as exc:
        raise BookendRenderError(
            f"bookend '{bookend['slot']}' ({composition}) render timed out "
            f"after {RENDER_TIMEOUT_SECONDS}s") from exc

    if result.returncode != 0:
        raise BookendRenderError(
            f"bookend '{bookend['slot']}' ({composition}) render failed: "
            f"{result.stderr[-500:]}")
    if not os.path.exists(out_path):
        raise BookendRenderError(
            f"bookend '{bookend['slot']}' ({composition}) reported success "
            f"but wrote no file at {out_path}")


def _render_engine_batch(pending: list, remotion_dir: str) -> None:
    """Render engine-composition bookends in ONE batch per composition.

    ``pending`` carries ``(bookend, props, out_path)`` triples.  The
    batch takes one composition per call, so triples are grouped by
    composition first - one bundle each, still one per composition
    rather than one per card.  A failed card raises
    :class:`BookendRenderError` naming the slot, the way the CLI path
    always has: a missing card is a hole in the picture, never a warning.
    """
    by_composition: dict[str, list] = {}
    for triple in pending:
        by_composition.setdefault(triple[0]["composition"], []).append(triple)
    repo_root = os.path.dirname(os.path.abspath(remotion_dir))
    for composition, triples in by_composition.items():
        jobs = [RenderJob(props=props, out_path=out_path)
                for _, props, out_path in triples]
        work_dir = os.path.dirname(os.path.abspath(triples[0][2]))
        try:
            results = render_batch(
                jobs, composition=composition, work_dir=work_dir,
                timeout=RENDER_TIMEOUT_SECONDS * max(1, len(jobs)),
                repo_root=repo_root)
        except RemotionBatchError as exc:
            slots = ", ".join(t[0]["slot"] for t in triples)
            raise BookendRenderError(
                f"could not render bookend(s) {slots} ({composition}): "
                f"{exc}") from exc
        by_out = {res.get("out"): res for res in results}
        for bookend, _, out_path in triples:
            res = by_out.get(out_path) or {}
            if not res.get("ok"):
                raise BookendRenderError(
                    f"bookend '{bookend['slot']}' ({composition}) render "
                    f"failed: "
                    f"{res.get('error', 'no result for this card')[:500]}")
            if not os.path.exists(out_path):
                raise BookendRenderError(
                    f"bookend '{bookend['slot']}' ({composition}) reported "
                    f"success but wrote no file at {out_path}")


def render_declared_bookends(structure: list, remotion_dir: str,
                             fps: int = 30, *, width: int,
                             height: int, stream=sys.stderr,
                             project_folder: str = "") -> list:
    """Produce every bookend the spine declares, and check the rest exist.

    Raises :class:`BookendRenderError` rather than warning: a missing card
    is a hole in the picture, and the two gates that would catch it later
    - the coverage assertion in ``compile_manifest`` and the black-frame
    probe in step 6.02 - both cost a full compile or a full render first.

    Engine compositions render in ONE batch per composition (see
    :func:`render_bookend` for which path each bookend takes); results
    come back in spine order either way.
    """
    engine_pending: list = []
    engine_props: dict[str, dict] = {}
    project_results: dict[str, dict] = {}
    order: list[str] = []
    for block in bookend_blocks(structure):
        bookend = block_bookend(block)
        if bookend["mode"] == "asset":
            if not os.path.exists(bookend["asset_path"]):
                raise BookendRenderError(
                    f"bookend '{bookend['slot']}' declares the premade "
                    f"asset {bookend['asset_path']}, which does not exist")
            print(f"  Bookend [{bookend['slot']}]: premade asset "
                  f"{os.path.basename(bookend['asset_path'])}", file=stream)
            project_results[bookend["slot"]] = {
                "slot": bookend["slot"],
                "composition": "",
                "asset_path": bookend["asset_path"],
                "props_path": "",
                "bytes": os.path.getsize(bookend["asset_path"]),
            }
            order.append(bookend["slot"])
            continue

        print(f"  Bookend [{bookend['slot']}]: rendering "
              f"{bookend['composition']} "
              f"({bookend['duration_seconds']}s)", file=stream)
        if bookend.get("source_path"):
            record = render_bookend(bookend, remotion_dir, fps,
                                    width=width, height=height,
                                    project_folder=project_folder)
            print(f"    OK: {record['asset_path']} ({record['bytes']} bytes)",
                  file=stream)
            project_results[bookend["slot"]] = record
            order.append(bookend["slot"])
            continue
        out_path = bookend["asset_path"]
        os.makedirs(os.path.dirname(out_path), exist_ok=True)
        props = bookend_props(bookend, fps, width, height)
        props_path = os.path.join(
            os.path.dirname(out_path), f"{bookend['slot']}_props.json")
        with open(props_path, "w", encoding="utf-8") as f:
            json.dump(props, f, indent=2, sort_keys=True)
        engine_pending.append((bookend, props, out_path))
        engine_props[bookend["slot"]] = {
            "composition": bookend["composition"],
            "asset_path": out_path,
            "props_path": props_path,
        }
        order.append(bookend["slot"])

    if engine_pending:
        # Engine compositions WITH a HyperFrames form draw through it
        # under that selection, one card at a time; everything else
        # batches through Remotion exactly as before. A composition
        # the selection cannot draw is not skipped - it joins the
        # batch, so the fallback is placement, never absence.
        hf_pending, batch_pending = [], []
        for triple in engine_pending:
            (hf_pending if _hyperframes_draws(
                triple[0]["composition"], project_folder)
             else batch_pending).append(triple)
        for bookend, props, out_path in hf_pending:
            _render_engine_hyperframes(bookend, bookend["composition"],
                                       remotion_dir, out_path, props,
                                       project_folder)
        if batch_pending:
            _render_engine_batch(batch_pending, remotion_dir)
        for bookend, _, out_path in engine_pending:
            meta = engine_props[bookend["slot"]]
            print(f"    OK: {out_path} ({os.path.getsize(out_path)} bytes)",
                  file=stream)
            project_results[bookend["slot"]] = {
                "slot": bookend["slot"],
                "composition": meta["composition"],
                "asset_path": out_path,
                "props_path": meta["props_path"],
                "bytes": os.path.getsize(out_path),
            }
    return [project_results[slot] for slot in order]
