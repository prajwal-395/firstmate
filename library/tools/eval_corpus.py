def _rung_ids(rung: int) -> list:
    """Request ids for a rung. 0 is every judged request; 6 is all."""
    if rung == 6:
        return [r["id"] for r in REQUESTS]
    if rung == 0:
        return [r["id"] for r in REQUESTS if r["scout_mode"] != "classified"]
    wanted = set(RUNGS[rung]["clusters"])
    ids = []
    for cluster in CLUSTERS:
        if cluster["id"] in wanted:
            ids.extend(cluster["requests"])
    return ids


def select(domain=None, level=None, rung=None, cluster=None,
           verdict=None, request_id=None):
    """The selectable subsets the harness promises: one request, a
    domain, a level, a rung, a cluster, or a scout verdict. Filters
    intersect. Unknown keys raise rather than selecting nothing."""
    ids = [r["id"] for r in REQUESTS]
    if request_id is not None:
        known = set(ids)
        wanted = [request_id] if isinstance(request_id, str) else list(request_id)
        unknown = [i for i in wanted if i not in known]
        if unknown:
            raise KeyError(f"unknown request id(s): {unknown}")
        ids = [i for i in ids if i in set(wanted)]
    if domain is not None:
        wanted = {domain} if isinstance(domain, str) else set(domain)
        known = {r["domain"] for r in REQUESTS}
        unknown = set(wanted) - known
        if unknown:
            raise KeyError(f"unknown domain(s): {sorted(unknown)}")
        ids = [i for i in ids if _by_id(i)["domain"] in wanted]
    if level is not None:
        wanted = {int(level)} if isinstance(level, int) else {int(v) for v in level}
        if wanted - {1, 2, 3}:
            raise KeyError(f"unknown level(s): {sorted(wanted)}")
        ids = [i for i in ids if _by_id(i)["level"] in wanted]
    if rung is not None:
        if rung not in RUNGS:
            raise KeyError(f"unknown rung: {rung}")
        keep = set(_rung_ids(rung))
        ids = [i for i in ids if i in keep]
    if cluster is not None:
        wanted = {cluster} if isinstance(cluster, str) else set(cluster)
        known = {c["id"] for c in CLUSTERS}
        unknown = set(wanted) - known
        if unknown:
            raise KeyError(f"unknown cluster(s): {sorted(unknown)}")
        keep = set()
        for c in CLUSTERS:
            if c["id"] in wanted:
                keep.update(c["requests"])
        ids = [i for i in ids if i in keep]
    if verdict is not None:
        wanted = {verdict} if isinstance(verdict, str) else set(verdict)
        if wanted - {"F", "P", "X"}:
            raise KeyError(f"unknown verdict(s): {sorted(wanted)}")
        ids = [i for i in ids if _by_id(i)["scout_verdict"] in wanted]
    return [_by_id(i) for i in ids]


_BY_ID = {r["id"]: r for r in REQUESTS}


def _by_id(request_id: str) -> dict:
    return _BY_ID[request_id]

