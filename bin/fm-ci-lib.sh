#!/usr/bin/env bash
# Shared helpers for the PR build-verdict watch: artifact paths, the sidecar
# record, the single-fire marker, and the watcher shim.
#
# The watch exists so a crewmate never spends model turns re-asking a forge
# whether CI finished. bin/fm-ci-check.sh arms it, bin/fm-ci-poll.sh runs it,
# and each of those owns its own command line and semantics.

FM_CI_WATCH_MAGIC=fm-ci-watch-v1

# The sidecar's fields after a successful fm_ci_watch_read.
FM_CI_WATCH_URL=
FM_CI_WATCH_ARMED_AT=

# A destructive or published path is never assembled from unguarded variables:
# an empty state root or an empty task id would name a file nobody asked for.
# These guards assert the facts that make a path ours - the root is a real
# directory, the id is path-safe, the suffix is one this layer publishes - and
# refuse rather than trusting the shape of a string.
fm_ci_state_root_valid() {  # <state>
  local state=${1-}
  [ -n "$state" ] || return 1
  case "$state" in
    /*) ;;
    *) return 1 ;;
  esac
  [ -d "$state" ] && [ ! -L "$state" ]
}

fm_ci_artifact_path() {  # <state> <task> <suffix>
  local state=${1-} task=${2-} suffix=${3-} parent
  FM_CI_ARTIFACT=
  fm_ci_state_root_valid "$state" || return 1
  fm_pr_task_id_valid "$task" || return 1
  case "$suffix" in
    .check.sh|.check-trust|.ci-watch|.ci-watch-fired) ;;
    *) return 1 ;;
  esac
  parent=$(cd "$state" 2>/dev/null && pwd -P) || return 1
  [ -n "$parent" ] || return 1
  FM_CI_ARTIFACT="$parent/$task$suffix"
}

# True when the file is a plain, single-link, non-symlink file - the shape this
# layer publishes and the only shape it will remove.
fm_ci_plain_file() {  # <path>
  local path=${1-}
  [ -n "$path" ] || return 1
  [ -f "$path" ] && [ ! -L "$path" ] || return 1
  [ "$(fm_pr_file_link_count "$path")" = 1 ]
}

fm_ci_remove_artifact() {  # <state> <task> <suffix>
  fm_ci_artifact_path "${1-}" "${2-}" "${3-}" || return 1
  [ -e "$FM_CI_ARTIFACT" ] || [ -L "$FM_CI_ARTIFACT" ] || return 0
  fm_ci_plain_file "$FM_CI_ARTIFACT" || return 1
  rm -f -- "$FM_CI_ARTIFACT"
}

# Read the watch sidecar and revalidate every field. The poll never trusts the
# stored URL: it is re-parsed here and the caller re-derives the request from
# the parsed components, so a doctored sidecar cannot aim the poll at another
# host or project.
fm_ci_watch_read() {  # <state> <task>
  local first url armed
  FM_CI_WATCH_URL=
  FM_CI_WATCH_ARMED_AT=
  fm_ci_artifact_path "${1-}" "${2-}" .ci-watch || return 1
  fm_ci_plain_file "$FM_CI_ARTIFACT" || return 1
  exec 8< "$FM_CI_ARTIFACT" || return 1
  IFS= read -r first <&8 || { exec 8<&-; return 1; }
  IFS= read -r url <&8 || { exec 8<&-; return 1; }
  IFS= read -r armed <&8 || { exec 8<&-; return 1; }
  if IFS= read -r _extra <&8; then
    exec 8<&-
    return 1
  fi
  exec 8<&-
  [ "$first" = "$FM_CI_WATCH_MAGIC" ] || return 1
  case "$armed" in
    ''|*[!0-9]*) return 1 ;;
  esac
  fm_pr_url_parse "$url" || return 1
  # Consumed by bin/fm-ci-poll.sh and bin/fm-ci-check.sh.
  # shellcheck disable=SC2034
  FM_CI_WATCH_URL=$FM_PR_URL
  # shellcheck disable=SC2034
  FM_CI_WATCH_ARMED_AT=$armed
}

fm_ci_watch_armed() {  # <state> <task>
  fm_ci_watch_read "${1-}" "${2-}" >/dev/null 2>&1
}

# ---------------------------------------------------------------------------
# The watcher shim
# ---------------------------------------------------------------------------

# The watcher copies a registered custom check to a randomly named snapshot
# before running it, so the check cannot derive its own task from $0 the way
# bin/fm-pr-poll.sh does. The home and task id are passed as arguments instead,
# shell-quoted; the id has already passed fm_pr_task_id_valid before reaching
# here. No PR data is interpolated: it stays in the sidecar.
fm_ci_shim_content() {  # <home> <root> <task>
  local home=$1 root=$2 task=$3
  printf '%s\n' \
    '#!/usr/bin/env bash' \
    '# Auto-generated by fm-ci-check.sh - PR build-verdict wake shim.' \
    '# The watcher runs this each check cycle; output becomes a check: wake.' \
    "export FM_HOME=$(printf '%q' "$home")" \
    "exec $(printf '%q' "$root/bin/fm-ci-poll.sh") --task $(printf '%q' "$task")"
}

fm_ci_shim_matches() {  # <file> <home> <root> <task>
  local file=$1
  [ -f "$file" ] && [ ! -L "$file" ] || return 1
  cmp -s "$file" <(fm_ci_shim_content "$2" "$3" "$4")
}
